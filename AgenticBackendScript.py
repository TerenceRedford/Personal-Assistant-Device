def close_recording(state: RecordingState) -> Path | None:
    output_path = state.path
    if state.wav_file is not None:
        state.wav_file.close()

    if state.path and state.started_at is not None:
        duration = state.bytes_written / (SAMPLE_RATE * CHANNELS * SAMPLE_WIDTH)
        elapsed = time.monotonic() - state.started_at
        log("recording", "saved", file=state.path.name, duration=f"{duration:.2f}s", elapsed=f"{elapsed:.2f}s", bytes=state.bytes_written)

    state.wav_file = None
    state.path = None
    state.started_at = None
    state.bytes_written = 0
    return output_path


def start_recording(state: RecordingState) -> None:
    close_recording(state)
    state.path = new_recording_path()
    state.wav_file = wave.open(str(state.path), "wb")
    state.wav_file.setnchannels(CHANNELS)
    state.wav_file.setsampwidth(SAMPLE_WIDTH)
    state.wav_file.setframerate(SAMPLE_RATE)
    state.started_at = time.monotonic()
    state.bytes_written = 0
    log("recording", "start", file=state.path.name)


def append_audio(state: RecordingState, payload: bytes) -> None:
    if state.wav_file is None:
        return
    state.wav_file.writeframes(payload)
    state.bytes_written += len(payload)



def search_openverse_images(query: str, limit: int) -> list[dict[str, Any]]:
    page_size = max(1, min(limit, 20))
    params = urlencode({"q": query, "page_size": page_size})
    search_url = f"{OPENVERSE_IMAGE_SEARCH_URL}?{params}"
    request = Request(search_url, headers={"User-Agent": "Mozilla/5.0 Stage4CalendarPipeline/1.0"})

    with urlopen(request, timeout=20) as response:
        payload = response.read().decode("utf-8", errors="replace")

    data = json.loads(payload)
    results = data.get("results") or []
    output: list[dict[str, Any]] = []
    for result in results:
        if isinstance(result, dict):
            output.append(result)
    return output


def tool_lookup_save_image(arguments: dict[str, Any]) -> dict[str, Any]:
    try:
        query = str(arguments.get("query", "")).strip()
        title = str(arguments.get("title", "")).strip()
        creator = str(arguments.get("creator", "")).strip()
        license_name = str(arguments.get("license", "")).strip().lower()
        source = str(arguments.get("source", "openverse")).strip().lower() or "openverse"

        try:
            limit = int(arguments.get("limit", 5))
        except Exception:
            limit = 5
        limit = max(1, min(limit, 20))

        try:
            selected_index = int(arguments.get("index", 0))
        except Exception:
            selected_index = 0

        if source != "openverse":
            raise ValueError("only the openverse source is supported right now")

        search_terms = query or title or creator
        if not search_terms:
            raise ValueError("query, title, or creator is required")

        log("images", "search start", query=search_terms, source=source, limit=limit)

        results = search_openverse_images(search_terms, limit)
        matches: list[dict[str, Any]] = []

        for result in results:
            result_title = str(result.get("title", "")).strip()
            result_creator = str(result.get("creator", "")).strip()
            result_license = str(result.get("license", "")).strip().lower()

            if title and title.lower() not in result_title.lower():
                continue
            if creator and creator.lower() not in result_creator.lower():
                continue
            if license_name and license_name not in result_license:
                continue

            matches.append(result)

        if not matches:
            return {"ok": False, "error": "no matching images found"}

        selected_index = max(0, min(selected_index, len(matches) - 1))
        selected = matches[selected_index]
        image_url = str(
            selected.get("thumbnail")
            or selected.get("thumbnail_url")
            or selected.get("url")
            or ""
        ).strip()
        if not image_url:
            raise ValueError("selected result did not include an image url")

        image_bytes = fetch_url_bytes(image_url)
        with Image.open(BytesIO(image_bytes)) as downloaded:
            image = downloaded.convert("RGB")

        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        saved_name = sanitize_filename_component(str(selected.get("title") or search_terms))
        saved_path = SCREENSHOTS_DIR / f"{saved_name}_{timestamp}.png"
        image.save(saved_path, format="PNG")

        metadata = {
            "query": query,
            "title": str(selected.get("title", "")),
            "creator": str(selected.get("creator", "")),
            "license": str(selected.get("license", "")),
            "source": source,
            "image_url": image_url,
            "page_url": str(selected.get("foreign_landing_url", "")),
            "saved_path": str(saved_path),
        }
        saved_path.with_suffix(".json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")

        log(
            "images",
            "saved",
            title=metadata["title"] or "(untitled)",
            creator=metadata["creator"] or "(unknown)",
            license=metadata["license"] or "(unknown)",
            path=saved_path.name,
            source_url=image_url,
        )

        return {"ok": True, "saved_path": str(saved_path), "metadata": metadata, "match_count": len(matches)}
    except (URLError, TimeoutError, OSError, json.JSONDecodeError, ValueError) as exc:
        log("images", "save failed", error=exc)
        return {"ok": False, "error": str(exc)}



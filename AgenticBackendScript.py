def month_events_for_render(current_year: int, current_month: int) -> list[dict[str, Any]]:
    events = load_calendar().get("events", [])
    output: list[dict[str, Any]] = []

    for event in events:
        try:
            event_date = datetime.strptime(event["date"], "%Y-%m-%d").date()
            event_time = validate_time_str(event["time"])
            recurrence = normalize_recurrence(event.get("recurrence"))
            title = str(event.get("title", "")).strip()
            if not title:
                continue

            if recurrence == "none":
                if event_date.year == current_year and event_date.month == current_month:
                    output.append(
                        {
                            "day": event_date.day,
                            "time": event_time,
                            "title": title,
                            "recurrence": recurrence,
                        }
                    )
            elif recurrence == "yearly":
                if event_date.month == current_month:
                    output.append(
                        {
                            "day": event_date.day,
                            "time": event_time,
                            "title": title,
                            "recurrence": recurrence,
                        }
                    )
        except Exception:
            continue

    output.sort(key=lambda e: (e["day"], e["time"], e["title"]))
    return output


def render_calendar_image(
    status_line: str,
    focus_year: int | None = None,
    focus_month: int | None = None,
    assistant_line: str = "",
) -> Image.Image:
    now = datetime.now()
    year = focus_year if focus_year is not None else now.year
    month = focus_month if focus_month is not None else now.month
    month_name = calendar_module.month_name[month]

    image = Image.new("RGB", (DISPLAY_WIDTH, DISPLAY_HEIGHT), (242, 244, 247))
    draw = ImageDraw.Draw(image)

    header_bg = (32, 72, 122)
    draw.rectangle((0, 0, DISPLAY_WIDTH - 1, 46), fill=header_bg)
    draw.text((10, 12), f"{month_name} {year}", fill=(255, 255, 255))
    draw.text((205, 12), "STAGE 4", fill=(255, 255, 255))

    weekdays = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
    cell_width = DISPLAY_WIDTH // 7
    grid_top = 58
    row_height = 30

    for i, wd in enumerate(weekdays):
        draw.text((i * cell_width + 6, 48), wd, fill=(0, 0, 0))

    month_grid = calendar_module.monthcalendar(year, month)

    for row_idx, week in enumerate(month_grid):
        y0 = grid_top + row_idx * row_height
        y1 = y0 + row_height
        draw.line((0, y1, DISPLAY_WIDTH, y1), fill=(180, 180, 180), width=1)
        for col_idx, day_num in enumerate(week):
            x0 = col_idx * cell_width
            x1 = x0 + cell_width
            draw.line((x1, grid_top - row_height // 2, x1, grid_top + 6 * row_height), fill=(180, 180, 180), width=1)
            if day_num > 0:
                draw.text((x0 + 4, y0 + 4), str(day_num), fill=(0, 0, 0))

    events = month_events_for_render(year, month)
    days_with_events = {event["day"] for event in events}
    log("render", "calendar", month=f"{month_name} {year}", event_count=len(events), status=status_line, assistant=assistant_line)

    for row_idx, week in enumerate(month_grid):
        y0 = grid_top + row_idx * row_height
        for col_idx, day_num in enumerate(week):
            if day_num <= 0 or day_num not in days_with_events:
                continue
            x0 = col_idx * cell_width
            draw.ellipse((x0 + cell_width - 10, y0 + 4, x0 + cell_width - 4, y0 + 10), fill=(200, 40, 40))

    list_top = 258
    draw.rectangle((0, list_top - 2, DISPLAY_WIDTH - 1, DISPLAY_HEIGHT - 1), fill=(255, 255, 255))
    draw.text((8, list_top + 2), "Events", fill=(20, 20, 20))
    draw.rounded_rectangle((12, 214, 307, 250), radius=8, fill=(236, 242, 250), outline=(32, 72, 122), width=2)
    draw.text((22, 223), "HERMES", fill=(32, 72, 122))
    if assistant_line:
        draw.text((88, 223), assistant_line[:28], fill=(20, 20, 20))

    if events:
        for idx, event in enumerate(events[:8]):
            suffix = " (Y)" if event["recurrence"] == "yearly" else ""
            line = f"{event['day']:02d} {event['time']} {event['title']}{suffix}"
            draw.text((8, list_top + 20 + idx * 20), line[:46], fill=(40, 40, 40))
    else:
        draw.text((8, list_top + 24), "No events this month", fill=(90, 90, 90))

    draw.rectangle((0, DISPLAY_HEIGHT - 26, DISPLAY_WIDTH - 1, DISPLAY_HEIGHT - 1), fill=(230, 235, 241))
    draw.text((6, DISPLAY_HEIGHT - 20), status_line[:58], fill=(0, 0, 0))

    return image


def rgb888_to_rgb565_le_bytes(rgb_image: Image.Image) -> bytes:
    rgb = rgb_image.convert("RGB")
    output = bytearray(rgb.width * rgb.height * 2)
    index = 0

    for r, g, b in rgb.getdata():
        value = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        output[index] = value & 0xFF
        output[index + 1] = (value >> 8) & 0xFF
        index += 2

    return bytes(output)


def build_img0_packet(image: Image.Image) -> bytes:
    if image.size != (DISPLAY_WIDTH, DISPLAY_HEIGHT):
        image = image.resize((DISPLAY_WIDTH, DISPLAY_HEIGHT), Image.Resampling.BILINEAR)

    payload = rgb888_to_rgb565_le_bytes(image)
    expected_len = DISPLAY_WIDTH * DISPLAY_HEIGHT * 2
    if len(payload) != expected_len:
        raise ValueError(f"bad payload length {len(payload)} (expected {expected_len})")

    header = struct.pack("<4sHHI", IMAGE_MAGIC, DISPLAY_WIDTH, DISPLAY_HEIGHT, len(payload))
    return header + payload


def send_pil_image_frame(sock: socket.socket, image: Image.Image, label: str = "image") -> None:
    if image.mode != "RGB":
        image = image.convert("RGB")
    if image.size != (DISPLAY_WIDTH, DISPLAY_HEIGHT):
        image = ImageOps.fit(image, (DISPLAY_WIDTH, DISPLAY_HEIGHT), method=Image.Resampling.LANCZOS)

    packet = build_img0_packet(image)
    sock.sendall(packet)
    log("img0", "sent", bytes=len(packet), width=DISPLAY_WIDTH, height=DISPLAY_HEIGHT, label=label)



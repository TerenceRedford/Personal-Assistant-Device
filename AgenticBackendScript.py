def newest_calendar_event_date() -> date | None:
    calendar_data = load_calendar()
    events = calendar_data.get("events", [])
    latest_date: date | None = None

    for event in events:
        if not isinstance(event, dict):
            continue
        date_text = str(event.get("date", "")).strip()
        try:
            event_date = datetime.strptime(date_text, "%Y-%m-%d").date()
        except Exception:
            continue

        if latest_date is None or event_date > latest_date:
            latest_date = event_date

    return latest_date



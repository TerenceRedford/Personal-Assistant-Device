def message_to_dict(message_obj: Any) -> dict[str, Any]:
    if isinstance(message_obj, dict):
        return message_obj

    if hasattr(message_obj, "model_dump"):
        dumped = message_obj.model_dump(exclude_none=True)
        if isinstance(dumped, dict):
            return dumped

    return {
        "role": "assistant",
        "content": getattr(message_obj, "content", "") or "",
        "tool_calls": getattr(message_obj, "tool_calls", None),
    }


def extract_tool_calls(message_dict: dict[str, Any]) -> list[tuple[str, dict[str, Any]]]:
    calls = []
    raw_calls = message_dict.get("tool_calls") or []

    for call in raw_calls:
        if isinstance(call, dict):
            function_part = call.get("function") or {}
            name = function_part.get("name")
            arguments = function_part.get("arguments") or {}
        else:
            function_part = getattr(call, "function", None)
            name = getattr(function_part, "name", None)
            arguments = getattr(function_part, "arguments", {}) if function_part else {}

        if isinstance(arguments, str):
            try:
                arguments = json.loads(arguments)
            except json.JSONDecodeError:
                arguments = {}

        if not isinstance(arguments, dict):
            arguments = {}

        if isinstance(name, str) and name:
            calls.append((name, arguments))

    return calls


